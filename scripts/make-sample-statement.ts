// Regenerates src/server/statements/sample-statement.ts from the demo dataset and the benchmark simulator.
//   npm run sample:statement
// The output is deterministic. tests/server/sample-statement.test.ts fails when the committed file and this script's output differ.
import { writeFileSync } from "node:fs";
import { buildSampleStatement } from "../src/domain/matching/sample-statement";

const lines = buildSampleStatement().trimEnd().split("\n");
const body = `// GENERATED by scripts/make-sample-statement.ts (npm run sample:statement). Do not edit by hand: a test regenerates it and compares.
// A sample bank statement of ${lines.length - 1} rows dated 20 to 27 October 2026 for the demo society. Every name and number is fictional.

export const SAMPLE_STATEMENT_LINES: readonly string[] = [
${lines.map((line) => `  ${JSON.stringify(line)},`).join("\n")}
];

/** The sample statement as CSV text, ready to upload (the UI task offers it as "Use the sample statement"). */
export function getSampleStatement(): string {
  return \`\${SAMPLE_STATEMENT_LINES.join("\\n")}\\n\`;
}
`;
writeFileSync(new URL("../src/server/statements/sample-statement.ts", import.meta.url), body);
console.log(`wrote ${lines.length - 1} rows`);
